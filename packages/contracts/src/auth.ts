// Canonical Phase 2 endpoint definitions. Original Zod schemas remain authoritative:
// no OpenAPI projection is allowed to replace executable checks in a runtime client.
import { makeApiConfig, type IMethod, type IBody, type IParams, type IQuery } from 'km-api';
import * as v from '@boro-biya/validation';

type ParseSchema = IBody & { parse(value: unknown): unknown };
type ObjectSchema = IParams & ParseSchema;
export type AuthProtection = 'public' | 'csrf' | 'bearer' | 'refresh' | 'setup' | 'recovery' | 'reset';

function endpoint<
  B extends ParseSchema,
  R extends ParseSchema,
  P extends ObjectSchema,
  Q extends ObjectSchema & IQuery,
>(
  operationId: string,
  method: IMethod,
  pathShape: string,
  body: B,
  success: R,
  successStatus: 200 | 201 | 202 | 204,
  protection: AuthProtection,
  params: P,
  query: Q,
  permission?: (typeof v.administrativePermissionKeys)[number],
) {
  const spec = makeApiConfig({
    operationId,
    method,
    pathShape,
    tags: ['#auth'],
    auth: protection === 'public' || protection === 'csrf' ? 'NO' : 'YES',
    requestContentType: 'application/json',
    responseContentType: 'application/json',
    request: { body, params, query, headers: v.emptyParametersSchema, cookies: v.emptyParametersSchema },
    response: {
      [successStatus]: success,
      400: v.errorEnvelopeSchema,
      401: v.errorEnvelopeSchema,
      403: v.errorEnvelopeSchema,
      404: v.errorEnvelopeSchema,
      409: v.errorEnvelopeSchema,
      413: v.errorEnvelopeSchema,
      429: v.errorEnvelopeSchema,
      500: v.errorEnvelopeSchema,
      503: v.errorEnvelopeSchema,
    },
  });
  const csrfRequired =
    method !== 'GET' &&
    ((protection !== 'public' && protection !== 'bearer') || operationId === 'securityStreamTicket');
  return { spec, success, successStatus, protection, permission, csrfRequired };
}

