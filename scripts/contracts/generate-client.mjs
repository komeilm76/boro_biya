// Run with: bun --tsconfig-override tsconfig.base.json scripts/contracts/generate-client.mjs [--check]
// Original endpoint schemas, never their lossy JSON Schema projections, drive the bindings.
import { readFile, writeFile } from 'node:fs/promises';
import { authOperations } from '../../packages/contracts/src/auth.ts';

const output = new URL('../../packages/api-client/src/generated/auth.ts', import.meta.url);
const methods = Object.keys(authOperations).map(
  (name) =>
    `    ${name}: (input: AuthOperationInput<typeof authOperations.${name}>) => executeAuthOperation(transport, authOperations.${name}, input),`,
);
const text = `// Generated by scripts/contracts/generate-client.mjs. Do not edit by hand.\nimport { authOperations } from '@boro-biya/contracts';\nimport { executeAuthOperation, type AuthOperationInput, type AuthTransport } from '../auth-operation.js';\n\nexport function createGeneratedAuthClient(transport: AuthTransport) {\n  return {\n${methods.join('\n')}\n  };\n}\n`;
// Use the repository's pinned formatter; generated code follows the same unchanged format check.
const { createRequire } = await import('node:module');
const require = createRequire(import.meta.url);
const { format, resolveConfig } = require('prettier');
const formatted = await format(text, { ...(await resolveConfig(output.pathname)), filepath: output.pathname });
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== formatted) throw new Error('Generated auth client is stale; regenerate it');
  console.log(`generated auth bindings: ${methods.length} operations match the endpoint source`);
} else {
  await writeFile(output, formatted);
}
